#     #发说说公开 内容   → 所有人可见
# ⚠ 默认已翻转（2026-09-19）：原默认公开、要私有得写「私」，她实测踩坑（A 发的 B 也看到）
#   ⇒ 二期本就是「每人一条私有」，默认不该是公开。想公开发就明写「公开」。
# 会真发一条说说，并把 NapCat 的 retcode 回给你。
# ⚠ 排期 / 选条 / LLM 兜底都还没做 —— 先验证风控让不让这个号发说说，
