#  🚦 并发错峰（2026-10-02 · 她报「我发消息会显示错误」查出来的）
# ============================================================
# 症状：她连着发两句，页面上蹦出一行
#   「（AI 接口出错：… request reached max organization concurrency: 1 …）」
#
# 根因（两层，缺一不成立）：
#   ① **上游**：这个 key 是**组织级并发上限 = 1** —— 同一瞬间只放一个请求进去。
#      ⚠⚠ 2026-10-02 下午**订正**（原来这里写的是「去 DeepSeek 平台提额」，**错了**）：
#         provider 那时已经是 **Kimi / Moonshot**（`.env` 的 `LLM_PROVIDER=kimi`）。
#         官方限速表（platform.moonshot.cn/docs/pricing/limits，按**累计充值**分档）：
#             Tier0（¥0）  并发 1   RPM 3    ← **就是这个档**
#             Tier1（¥50） 并发 15  RPM 100
#         ⇒ 她看到的**两个**报错（`concurrency: 1` 与 `max RPM: 3`）是同一档的两面。
#         ⇒ **根治 = 去 Kimi 控制台充值**（⚠ 代金券不计入累计充值），不用改代码。
#         下面这套错峰**仍然有用**（Tier1 的 15 并发也值得兜底），只是要认清：
#         「1.2 秒 × 2 次」这种退避**跨不过 RPM 的 60 秒窗口** ⇒ 对 RPM 类在**设计上**
#         就救不了（现已改成指数退避，但根治还是提额度）。
#   ② **我们这边有四个调用方抢这一个槽**：前台 `get_reply`（她在等的那条）、
#      后台「情绪判定」（**每一轮都起**，`MOOD_JUDGE_TIMEOUT`）、后台「单通摘要」
#      （挂断 / 补摘时起，timeout 30）、以及 8 轮摘要（在前台里同步跑）。
#      踩中的时序：她发第 N 句 → 回复一返回，情绪线程**立刻**占住唯一那个槽 →
#      她在这 8 秒内再发一句 ⇒ 前台请求进不去 ⇒ 被上游拒。
#
# ⚠⚠ 为什么这节住在 **config**（而不是引擎某个模块 / 网页端）：
#   它是**引擎与网页端共用**的机制 —— 后台线程一边在 `Rafayel_mood.spawn_update`、
#   一边在 `web/page/call.py` 的摘要线程里 ⇒ 两边必须用**同一把锁**才叫互斥。
#   引擎不许 import 网页端、网页端不许（随便）import 引擎 ⇒ 唯一能共用的地方就是 config
#   （它本来就在 `check_static` 的 `WEB_WHITELIST` 里：只读、**不开口子**）。
#   ⇒ 这是**零新增开口**的做法。另开一个模块反而要让 `call.py` 多 import 一个引擎模块，
#     那才是真从 ADR-22 红线上又漏一个口。
#
# ⭐ 三道闸（方案 A，她 2026-10-02 选的「A + 独立项 1」）：
#   ① 让路（`BG_GATE_DELAY_*`）：后台起线程后先随机小睡一下再打请求，
#      避开「前台刚收工」那一瞬 —— 成本最低、收益最大的一道。
#   ② 互斥（`bg_slot()` 里那把 `_BG_LOCK`）：同一时刻**只放一个后台请求**出去。
#      后台之间本来就不急，排队等一等没人在意；它们被拒才是真浪费。
#   ③ 重试（`LLM_RETRY*`，实现在 `Rafayel_llm.get_reply`）：前台撞上了就退避重试，
#      对她是无感的 —— 多等 1 秒，好过看见一行英文报错。
#
# ⚠ 改这几个值要重启进程才生效（跟其它开关一个口径）。
BG_GATE_ENABLE = True      # 关掉 ⇒ 后台不再让路/排队（回到 2026-10-02 之前的行为）
BG_GATE_DELAY_MIN = 1.0    # 让路：后台起线程后最少小睡几秒
BG_GATE_DELAY_MAX = 2.5    # 让路：最多小睡几秒（随机，免得几条后台总是同时醒）
LLM_RETRY = 2              # 前台撞上可重试的错，最多再试几次（0 = 不重试）
# ⚠⚠ 2026-10-02 下午改：原来写死 1.2 秒（只够应付「同一瞬间撞车」）。
#   她这次报的错换成 **RPM（每分钟请求数）** —— 那是**整整 60 秒的窗口**，
#   1.2 秒跨不过去；官方（platform.kimi.com 限速文档）也推荐**指数退避**。
#   ⇒ 改成指数：第 n 次等 `WAIT * BACKOFF ** (n-1)`（1s → 2s → 4s…）。
LLM_RETRY_WAIT = 1.0       # 第一次重试前等几秒（指数退避的**基值**）
LLM_RETRY_BACKOFF = 2.0    # 退避倍率（填 1.0 就退化成等长等待，跟老行为一样）
# ⚠ 单次等待的**硬上限**：上游偶尔会叫我们等几十秒（RPM 窗就是这个量级），
#   而她正盯着屏幕等这一句 ⇒ 宁可放弃、让显示层给人设化的降级话（见下面的
#   `LLM_BUSY_SAY`），也绝不让她干等 60 秒。
LLM_RETRY_MAX_WAIT = 20.0


_BG_LOCK = threading.Lock()


@contextlib.contextmanager
def bg_slot():
    """
    🚦 后台 LLM 请求的**闸门**（方案 A 的 ① 让路 + ② 互斥）。

    用法 —— ⚠⚠ **必须在拿 `_chat_lock` 之前**进闸：

        with bg_slot():
            with _chat_lock(uid):
                ...

    为什么顺序不能反：让路那一步是个 `sleep`，持着对话锁睡会把她下一条消息
    一起拖住（哪怕只有 1~2.5 秒，那也是白等的）。闸门只管「打模型这一刻」。

    ⚠ 本函数**不吞异常、不做重试**：后台请求失败就失败 —— 情绪沿用旧心情、
      摘要下次再补，这两件事本来就不需要成功（它们是锦上添花，不是她等的东西）。
      ⚠ 异常要由**调用方自己**包 try 吞掉：线程里的异常没人接。
    """
    if not BG_GATE_ENABLE:
        yield
        return
    time.sleep(random.uniform(BG_GATE_DELAY_MIN, BG_GATE_DELAY_MAX))
    with _BG_LOCK:
        yield


