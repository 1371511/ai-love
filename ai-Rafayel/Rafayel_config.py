# ============================================================
#  📣 主动打招呼（2026-09-18）
# ============================================================
# 他想不想先开口。关掉就改 AUTO_GREET = False，其余参数不用动。

AUTO_GREET = True               # 总开关
# ⚠ 这个门槛必须**比一晚睡眠长**（小辞定 16 小时）。以前设 6 小时时，
#   睡一觉 8~10 小时就算「冷场」⇒ 等于每天早上都满足条件，他会在你刚醒时冒出来。
#   16 小时的含义：睡一觉不算冷场，要真的「一整天没怎么说话」才会开口。
AUTO_GREET_IDLE_HOURS = 16
AUTO_GREET_MAX_PER_DAY = 1      # 每天最多主动发几条（保险丝；主判据是下面的排期）
AUTO_GREET_MIN_GAP_HOURS = 24   # 兜底硬下限：只在旧记录没有 next_at 时起作用
# 🎲 排期：每次发完就随机约好「下次最早什么时候」——从本次开口算起隔 48~72 小时
#    （2~3 天，按实际时长算），时刻在 8:00~22:59 之间随机。这才是**频率**的主判据：≈每周 2~3 次。
#    ⚠ 与上面的 IDLE_HOURS 是两个独立闸门：冷场门槛管「她是不是真走了」，排期管「我上次说过话够久了没」。
AUTO_GREET_GAP_DAYS_MIN = 2
AUTO_GREET_GAP_DAYS_MAX = 3
AUTO_GREET_HOUR_START = 8       # 只在 8:00–23:00 之间发，不半夜打扰
AUTO_GREET_HOUR_END = 23
AUTO_GREET_SCAN_SECONDS = 900   # 后台每 15 分钟扫一遍谁该被惦记了

# ⏱ 时区偏移（小时）——只影响主动打招呼，不动系统设置。
#   服务器（腾讯云 Ubuntu）默认很可能是 **UTC**，而上面那几个"几点"是**北京时间**。
#   不换算的话整体会偏 8 小时：北京早上 6~7 点收到「再不睡天就要亮了」，非常出戏。
#   → 服务器 `date` 显示 UTC 就填 8；显示 CST（已是北京时间）就改回 0。
#   ✅ 2026-09-18 实测：服务器 `date` = CST（北京时间）→ 定为 0，勿再改 8。
AUTO_GREET_TZ_OFFSET = 0


