def is_llm_error(text):
    """
    这句是「引擎替上游转述的报错」，还是他说的话？

    ⭐ 只给**显示层**用（通话页字幕 / 历史通话页 / 聊天气泡 / QQ 消息）——
      认出它 ⇒ 渲染时换成人设化的降级话（`LLM_BUSY_SAY`）+ 一行小字
      （`LLM_BUSY_HINT`），别把英文原文甩到她脸上。
    ⚠ 判据本体是 `LLM_ERR_MARKS`（上面三句模板的前缀，**现算**）
      ⇒ 以后改文案不用第二处跟着改。
    ⚠ 跟记忆侧**故意不合并**：`summarize_call` 也认 `LLM_ERR_MARKS`，但那边要的是
      「跳过、不摘进长期记忆」——一个换皮、一个丢弃，语义不同，别为了少写一行拧成一处。
    ⚠ **永不抛**：拿 `None` / 数字 / dict 来也返回 `False`（显示层遍地都在调它）。
    """
    return str(text or "").lstrip().startswith(LLM_ERR_MARKS)
