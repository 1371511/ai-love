# -*- coding: utf-8 -*-
"""
祁煜（Rafayel）系统的**配置与常量**层（2026-09-17 从 `Rafayel_chat.py` 拆出）。

本层是整条依赖链的**最底层**，不 import 本项目任何其它模块。
一旦它反向依赖了 profile / memory，就会出现
`Rafayel_profile ↔ Rafayel_memory` 的循环导入，整个包直接炸。

放三类东西：
  ① 路径 —— MEMORY_DIR（对话记忆与用户画像的落盘目录）
  ② 可调数值 —— 历史轮数 / 摘要间隔 / 生成上限 / 世界书注入预算
  ③ API 配置 —— 读 .env、默认 key、当前生效的 key

改参数只改这里，各模块 `from Rafayel_config import …` 拿。
"""

import os

from dotenv import load_dotenv

HERE = os.path.dirname(os.path.abspath(__file__))           # E:\ai-love\ai-Rafayel
# 2026-09-17 搬家：代码进 ai-Rafayel\，而 .env / memory\ 留在项目根 → 上跳一层。
ROOT = os.path.dirname(HERE)                                # E:\ai-love

# 2026-09-15 修：原来是无参 load_dotenv()，靠**当前工作目录**往上找 .env。
# 部署到服务器用 tmux/系统服务启动时 cwd 未必是项目目录，读不到就会退回 DEFAULT_API_KEY
# 那个假 key，表现为「每句都回 AI 接口出错」却查不出原因。改成按脚本自身位置定位。
load_dotenv(os.path.join(ROOT, ".env"))


# ============================================================
#  💾 路径
# ============================================================

MEMORY_DIR = os.path.join(ROOT, "memory")


# ============================================================
#  🔁 对话管理
# ============================================================

SUMMARY_INTERVAL = 8        # 每 8 轮对话触发一次摘要更新
MAX_HISTORY_TURNS = 12      # 保留最近 12 轮对话
MAX_FACTS = 20              # 最多保留 20 条关键事实
MAX_PROFILE_ITEMS = 12      # 用户画像每个分类最多留 12 条


# ============================================================
#  📏 生成长度
# ============================================================
# 2026-09-15 调：旧值两处都写死 300。
#   300 ≈ 200~400 字，祁煜那种「一句话 + 动作/神态描写」的结构经常被从中间切断，
#   断在未说完的半句上，比单纯短回复更出戏 —— 短也要短得完整。
#   ⚠ 调大只是**放开天花板**，不会让模型变啰嗦：实际长度由人设和 post_history 决定。
MAX_TOKENS = 1000           # 单次回复上限（≈ 600~1000 字）
SUMMARY_MAX_TOKENS = 600    # 摘要 + 画像补丁：prompt 更长，且比旧版多了一项「任务二」

# 2026-09-18 加：此前**从未传过** temperature，一直是 DeepSeek 默认的 1.0。
#   角色扮演在 1.0 下容易飘（语气忽冷忽热、偶尔冒出不合人设的说法）。
#   0.8 是「还留着活人感、但不乱跑」的档位，小辞定的。想更稳就往 0.6 调，想更有意外感回 1.0。
#   ⚠ 只作用于**回复**；摘要那条请求刻意不传（摘要要的是稳定复述，不是发挥）。
TEMPERATURE = 0.8


# ============================================================
#  📣 主动打招呼（2026-09-18）
# ============================================================
# 他想不想先开口。关掉就改 AUTO_GREET = False，其余参数不用动。

AUTO_GREET = True               # 总开关
AUTO_GREET_IDLE_HOURS = 6       # 冷场够这么久他才忍不住开口
AUTO_GREET_MAX_PER_DAY = 2      # 每天最多主动发几条
AUTO_GREET_MIN_GAP_HOURS = 4    # 两条主动消息之间至少隔多久
AUTO_GREET_HOUR_START = 8       # 只在 8:00–23:00 之间发，不半夜打扰
AUTO_GREET_HOUR_END = 23
AUTO_GREET_SCAN_SECONDS = 900   # 后台每 15 分钟扫一遍谁该被惦记了


# ============================================================
#  📚 世界书注入预算
# ============================================================
# 44 条全塞进去会把 token 撑爆，也没必要 —— 只注入本轮命中且分数最高的几条。
WB_MAX_CHARS = 1400         # 注入正文总字数上限
WB_MAX_ENTRIES = 6          # 最多注入几条


# ============================================================
#  🔑 API 配置
# ============================================================

API_URL = "https://api.deepseek.com/chat/completions"
MODEL = "deepseek-chat"

# 从环境变量读取 API Key，如果没有则使用默认值（仅供测试）
DEFAULT_API_KEY = "sk-需要替换成你自己的api密钥"
api_key = os.environ.get("DEEPSEEK_API_KEY", DEFAULT_API_KEY)
